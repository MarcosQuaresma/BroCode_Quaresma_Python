# Claculando a área de um retângulo:
print ("insira os dados do retangulo, para descobrirmos a área!")

b = float(input("Qual é a Base(b) do retangulo?"))
h =  float(input("Qual é a Altura(h) do retangulo?"))

A = b*h

print (f"Portanto a maneira que medimos a Área(A) do retangulo é a Base(b) x Altura(h): A = b * h.")
print (f"A Área do retangulo é de: {A} m²")

# Calculando o Volume de um bloco Bloco Retangular.
print ("Iremos calcular agora o Volume de um 'retangulo' em 3 dimenções, ou seja: um Bloco Retangular")

c = float(input("Qual é o comprimento do Bloco Retangular? "))
l = float(input("Qaual é a Largura do Bloco Retangular? "))
h = float(input("Qual é a Altura do Bloco Retangular? "))

V = c * l * h

print ("Portanto a maneira que medimos o Volume(V) do Bloco Retangular é o Comprimento(c) x Largura(l) x Altura(h)")
print (f"A formula é: V = c * l * h, o Resultado em cm³ é: {V} cm³")