#                 Indexação de String(str)
# Indexação = permite acessar elementos de uma sequencia usando um conjunto de colchetes [] (operador de indexação)
#             [start : end : step]

num_credito = "1234-5678-9012-3456"

print(num_credito[0])  # se eu quiser o primero caractere da Str.
print(num_credito[1])  # se eu quiser o segundo caractere da Str.
print(num_credito[4])  # se eu quiser o quinto caractere da Str.

print(num_credito[0:4])  # se eu quiser-mos os 4 primeiros caractere da Str.